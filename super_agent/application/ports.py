"""Application-owned outbound capability contracts."""

from __future__ import annotations

from collections.abc import Sequence
from typing import Protocol

from super_agent.application.values import AgentProfile, MCPServerSettings
from super_agent.runtime.protocol.provider import ProviderConfig
from super_agent.runtime.protocol.run_context import RunContext
from super_agent.runtime.protocol.types import Message, Model, ToolRunner
from super_agent.runtime.session import Session


class ModelResolver(Protocol):
    def model(self, provider: str, config: ProviderConfig) -> Model: ...


class InstructionSource(Protocol):
    def messages(self, base: str) -> list[Message]: ...


class ProviderPreferences(Protocol):
    @property
    def writable(self) -> bool: ...

    def save_provider(self, provider: str, api_key: str, model: str) -> ProviderConfig: ...


class MemoryPreferences(Protocol):
    def set_enabled(self, enabled: bool) -> None: ...


class MCPServer(Protocol):
    @property
    def name(self) -> str: ...
    @property
    def tools(self) -> tuple[str, ...]: ...


class MCPBackend(Protocol):
    def servers(self) -> Sequence[MCPServer]: ...
    async def connect(self, ctx: RunContext, name: str, settings: MCPServerSettings) -> Sequence[ToolRunner]: ...
    async def disconnect(self, name: str) -> Sequence[str]: ...
    def install(self, items: Sequence[ToolRunner]) -> None: ...
    def uninstall(self, names: Sequence[str]) -> None: ...
    async def restart(self, ctx: RunContext, name: str) -> None: ...
    def save(self, name: str, server: MCPServerSettings | None) -> None: ...


class DelegationEnvironment(Protocol):
    def model(self, profile: AgentProfile) -> Model: ...
    async def worktree(self, ctx: RunContext) -> str: ...
    async def child(self, profile: AgentProfile, prompt: str, cwd: str, model: Model) -> Session: ...
